const slug = (n) => n.toLowerCase().replace(/[^a-z0-9]+/g, '_');
const url = (n) => `https://cdn.jsdelivr.net/gh/microsoft/fluentui-emoji@main/assets/${encodeURIComponent(n)}/3D/${slug(n)}_3d.png`;

const missing = [];
for (const [name] of EMOJI) {
  const file = join(out, `${slug(name)}.png`);
  if (existsSync(file)) continue;
  const res = await fetch(url(name));
  if (!res.ok) { missing.push(name); continue; }
  writeFileSync(file, Buffer.from(await res.arrayBuffer()));
}

const have = EMOJI.filter(([n]) => !missing.includes(n));
const lines = [
  '// Generated by scripts/fetch-emoji.mjs. Fluent 3D emoji (MIT), keyed by library name and by emoji character.',
  '/* eslint-disable @typescript-eslint/no-require-imports */',
  'export const EMOJI_BY_NAME: Record<string, number> = {',
  ...have.map(([n]) => `  ${JSON.stringify(n)}: require('../../assets/emoji/${slug(n)}.png'),`),
  '};',
  'export const EMOJI_BY_CHAR: Record<string, string> = {',
  ...have.flatMap(([n, chars]) => chars.map((c) => `  ${JSON.stringify(c)}: ${JSON.stringify(n)},`)),
  '};',
  '',
];
writeFileSync(join(root, 'src', 'ui', 'emoji-assets.ts'), lines.join('\n'));
